#!/usr/bin/env python3
"""iOS two-pass export stubs (the counterpart of gen-export-stubs.py).

Loom's lean Release compiles code out (inspector, DevTools, tracing, Fabric's renderer internals) but its React
binary must still export every global symbol React Native's own binary of the same slice exports. A first build
(pass 1: no stubs, unresolved names tolerated via -undefined dynamic_lookup) shows which exports have no code;
this script writes a stub for each into a SwiftPM C target (loom-stubs/), and pass 2 links it.

  gen-export-stubs-ios.py --pass1 <stubs-dir>
      an empty stub target (it still carries the pass-1 linker flag)
  gen-export-stubs-ios.py <baseline.tar.gz> <pass1.xcframework> <out-dir>
      <out-dir>/<slice>/{loom_export_stubs.S,stub.c,include/LoomExportStubs.h} per slice of the baseline

A function stub is `mov x0, #0; ret` (xor eax/edx; ret), a data stub is zero-filled storage of the size the
baseline binary gave the symbol (distance to the next symbol).
Objective-C metadata and Swift symbols are never stubbed (Loom cuts no Objective-C or Swift).

Never stubbed either:
- WEAK definitions of the baseline (template and inline instantiations: std:: containers of folly::dynamic, ...).
  Every image that uses one carries its own copy, so none needs ours. Stubbing them is wrong, not just useless:
  clang emits most of them as weak_def_can_be_hidden, so pass 1 has them as LOCAL symbols, absent from its
  export table, and a weak stub then wins the link over the real code (a zero-returning
  unordered_map<folly::dynamic,...>::__construct_node crashed the app at launch).
- Anything pass 1 defines at all, exported or not.
"""
import os, re, subprocess, sys, tempfile

HEADER = "/* Generated by tools/prebuild/gen-export-stubs-ios.py. Do not edit. */\n"


def nm_exports(binary, arch, include_weak=True):
    """name -> (address, section) of every global defined symbol of one arch (strong only unless include_weak)."""
    out = subprocess.run(["nm", "-gUm", "-arch", arch, binary], capture_output=True, text=True, check=True).stdout
    syms = {}
    for line in out.splitlines():
        m = re.match(r"([0-9a-f]+) \((\S+),(\S+)\) (?:\[[^\]]*\] )?(weak )?(?:private )?external (?:\[[^\]]*\] )?(\S.*)$", line)
        if m and (include_weak or not m.group(4)):
            syms[m.group(5)] = (int(m.group(1), 16), m.group(2) + "," + m.group(3))
    return syms


def nm_defined(binary, arch):
    """Every symbol name the binary defines, exported or local."""
    out = subprocess.run(["nm", "-Uj", "-arch", arch, binary], capture_output=True, text=True, check=True).stdout
    return set(out.split())


def archs(binary):
    return subprocess.run(["lipo", "-archs", binary], capture_output=True, text=True, check=True).stdout.split()


def stub_text(arch, base, have, everything):
    ordered = sorted(base.items(), key=lambda kv: kv[1][0])
    addrs = sorted(v[0] for v in everything.values())
    lines = []
    count = 0
    for i, (name, (addr, section)) in enumerate(ordered):
        if name in have or re.search(r"[^A-Za-z0-9_$.]", name) or name.startswith(("_OBJC_", "_$s", "__$s", "l_OBJC")):
            continue
        if section == "__TEXT,__text":
            if arch == "arm64":
                body = "    .p2align 2\n%s:\n    mov x0, #0\n    mov x1, #0\n    ret\n" % name
            else:
                body = "    .p2align 4\n%s:\n    xorl %%eax, %%eax\n    xorl %%edx, %%edx\n    ret\n" % name
            lines.append("    .text\n    .globl %s\n    .weak_definition %s\n    .no_dead_strip %s\n%s" % (name, name, name, body))
        elif section.startswith(("__DATA", "__TEXT,__const", "__TEXT,__constg")):
            nxt = next((a for a in addrs if a > addr), addr + 8)
            size = min(max(nxt - addr, 8), 4096)
            lines.append("    .data\n    .globl %s\n    .weak_definition %s\n    .no_dead_strip %s\n    .p2align 3\n%s:\n    .space %d\n" % (name, name, name, name, size))
        else:
            continue
        count += 1
    return "".join(lines), count


def write_target(dirpath, asm):
    os.makedirs(os.path.join(dirpath, "include"), exist_ok=True)
    with open(os.path.join(dirpath, "loom_export_stubs.S"), "w") as f:
        f.write(HEADER + "    .subsections_via_symbols\n" + asm)
    with open(os.path.join(dirpath, "stub.c"), "w") as f:
        f.write(HEADER + '#include "LoomExportStubs.h"\n')
    with open(os.path.join(dirpath, "include", "LoomExportStubs.h"), "w") as f:
        f.write(HEADER + "#pragma once\n")


def main(baseline, pass1, out):
    tmp = tempfile.mkdtemp()
    subprocess.run(["tar", "xzf", baseline, "-C", tmp, "React.xcframework"], check=True)
    for slice_ in sorted(os.listdir(os.path.join(tmp, "React.xcframework"))):
        bin_b = os.path.join(tmp, "React.xcframework", slice_, "React.framework", "React")
        bin_p = os.path.join(pass1, slice_, "React.framework", "React")
        if not os.path.exists(bin_b):
            continue
        parts = []
        for arch in archs(bin_b):
            everything = nm_exports(bin_b, arch)          # for data sizes: distance to the next symbol
            base = nm_exports(bin_b, arch, include_weak=False)
            have = nm_defined(bin_p, arch)
            text, n = stub_text(arch, base, have, everything)
            cond = "defined(__arm64__)" if arch == "arm64" else "defined(__x86_64__)"
            parts.append("#if %s\n%s#endif\n" % (cond, text))
            print("%s/%s: %d stubs (RN strong exports %d of %d, pass 1 defines %d)" % (slice_, arch, n, len(base), len(everything), len(have)))
        write_target(os.path.join(out, slice_), "".join(parts))


if __name__ == "__main__":
    if sys.argv[1] == "--pass1":
        write_target(sys.argv[2], "")
    else:
        main(*sys.argv[1:4])
