#!/usr/bin/env python3
"""Generate weak no-op stubs for every dynamic symbol RN's own libreactnative.so exports.

Loom's lean release compiles code out (inspector, DevTools, tracing; later Fabric's renderer internals)
but must still export every name RN exports: libraries link against them. The generated assembly
defines each exported name as a WEAK symbol: a function returns zero (null/false/0 in the return
registers, nothing else is touched), a data symbol is zero-filled storage of the same size. It is linked
LAST, so a real definition (strong, or an earlier weak/inline one) always wins; a stub only ends up in
the library for a name whose real code was cut.

  gen-export-stubs.py <baseline.aar> <out-dir>      writes <out-dir>/<abi>/loom_export_stubs.s
"""
import os, re, subprocess, sys, tempfile, zipfile

NDK = os.environ.get("ANDROID_NDK") or os.path.join(os.environ["ANDROID_HOME"], "ndk", "28.2.13676358")
NM = next(os.path.join(r, "llvm-nm") for r, _, f in os.walk(os.path.join(NDK, "toolchains", "llvm", "prebuilt")) if "llvm-nm" in f)

HEAD = {
    "arm64-v8a": """\
    .text
    .p2align 2
    .type loom_export_noop,%function
loom_export_noop:
    mov x0, xzr
    mov x1, xzr
    fmov d0, xzr
    ret
""",
    "armeabi-v7a": """\
    .syntax unified
    .thumb
    .text
    .p2align 1
    .thumb_func
    .type loom_export_noop,%function
loom_export_noop:
    movs r0, #0
    movs r1, #0
    bx lr
""",
    "x86": """\
    .text
    .p2align 4
    .type loom_export_noop,@function
loom_export_noop:
    xorl %eax, %eax
    xorl %edx, %edx
    ret
""",
    "x86_64": """\
    .text
    .p2align 4
    .type loom_export_noop,@function
loom_export_noop:
    xorl %eax, %eax
    xorl %edx, %edx
    ret
""",
}
FUNC_TYPES = set("TtWw")
OBJ_TYPES = set("DdBbRrVvGgSs")

def write(out, abi, text, mode):
    d = os.path.join(out, abi)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "loom_export_stubs.s"), "w") as f:
        f.write("/* Generated by tools/prebuild/gen-export-stubs.py. Do not edit. */\n" + text)

def exports(lib):
    res = subprocess.run([NM, "-D", "--defined-only", "-S", lib], capture_output=True, text=True, check=True).stdout
    out = {}
    for l in res.splitlines():
        p = l.split()
        if len(p) == 4:
            out[p[3]] = (int(p[1], 16), p[2])
    return out

def main(aar, pass1, out):
    tmp = tempfile.mkdtemp()
    with zipfile.ZipFile(aar) as z:
        z.extractall(tmp, [n for n in z.namelist() if n.startswith("jni/") and n.endswith("/libreactnative.so")])
    for abi in sorted(os.listdir(os.path.join(tmp, "jni"))):
        base = exports(os.path.join(tmp, "jni", abi, "libreactnative.so"))
        have = exports(os.path.join(pass1, abi, "libreactnative.so"))
        lines = [HEAD[abi]]
        thumb = abi == "armeabi-v7a"
        n = 0
        for name, (size, typ) in sorted(base.items()):
            if name in have or re.search(r"[^A-Za-z0-9_$.]", name):
                continue
            if typ in FUNC_TYPES:
                lines.append(f"    .weak {name}\n    .type {name},%function\n    .{'thumb_set' if thumb else 'set'} {name}, loom_export_noop\n")
            elif typ in OBJ_TYPES:
                lines.append(f'    .section .bss.{name},"aw",%nobits\n    .weak {name}\n    .type {name},%object\n    .p2align 3\n{name}:\n    .skip {size}\n    .size {name},{size}\n')
            else:
                continue
            n += 1
        write(out, abi, "".join(lines), "final")
        print(f"{abi}: {n} stubs (RN exports {len(base)}, pass 1 has {len(have)})")
    open(os.path.join(out, "mode.txt"), "w").write("final\n")

if __name__ == "__main__":
    if sys.argv[1] == "--pass1":
        for abi in HEAD:
            write(sys.argv[2], abi, "    .text\n", "pass1")
        open(os.path.join(sys.argv[2], "mode.txt"), "w").write("pass1\n")
    else:
        main(sys.argv[1], sys.argv[2], sys.argv[3])
